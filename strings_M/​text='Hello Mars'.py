text1 = 'Hello Mars'

print(text1[0]) # prints the first character of the string.​

print(text1[4:7]) # prints the 5th, 6th, and 7th characters of the string.​

print(text1[8::]) # prints the 9th to the last character.​

print(text1[-2]) # prints the second to last character of the string.​

print(text1[:7]) # prints the characters with indexes 0 to 7 (not including 7).​

print(text1[8:]) # prints all characters after the starting index.​

print(text1[0:8:2]) # slices the characters with indexes 0, 2, 4, and 6.​